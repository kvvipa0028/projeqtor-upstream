def fold_ascii(word):
    import unicodedata
    stripped = "".join(ch for ch in unicodedata.normalize("NFD", word) if unicodedata.category(ch) != "Mn")
    return stripped.lower().strip("'")


def lookup_word(word):
    if word and all(0xE000 <= ord(ch) <= 0xF8FF for ch in word):
        return word
    lower = fold_ascii(word)
    if lower in EXTRA_WORDS:
        return EXTRA_WORDS[lower]
    if lower in WORDS:
        return WORDS[lower]
    if lower in KEEP:
        return word
    if lower in TYPO_WORDS:
        return TYPO_WORDS[lower]
    if lower.endswith("'s") and lookup_word(lower[:-2]) not in (None, word):
        return lookup_word(lower[:-2])
    if lower.endswith("ies") and (lower[:-3] + "y") in WORDS:
        return WORDS[lower[:-3] + "y"]
    # Only strip a trailing s when it is a real plural. "news" must not become "new".
    if lower.endswith("s") and lower not in {"news", "series", "species", "means", "this", "status"}:
        stem = lower[:-1]
        if stem in EXTRA_WORDS and EXTRA_WORDS[stem]:
            return EXTRA_WORDS[stem]
        if stem in WORDS and WORDS[stem]:
            return WORDS[stem]
    if re.fullmatch(r"[A-Z]{2,}", word) or (word and word[0].islower() is False and any(ch.isupper() for ch in word[1:])):
        return word
    return None


def translate_fragment(text):
    """Translate a short UI fragment. Markers PHX…XPH are left untouched."""
    source = text.strip()
    if not source:
        return ""
    if source and all(0xE000 <= ord(ch) <= 0xF8FF for ch in source):
        return source

    def paren(match):
        return "（" + translate_fragment(match.group(1)) + "）"

    source = re.sub(r"\(([^()]*)\)", paren, source)
    source = re.sub(r"\s+", " ", source).strip()

    patterns = [
        (r"(?i)^types? of (.+)$", lambda m: translate_fragment(m.group(1)) + "类型"),
        (r"(?i)^list of (.+)$", lambda m: translate_fragment(m.group(1)) + "列表"),
        (r"(?i)^(.+?) per (.+)$", lambda m: "按" + translate_fragment(m.group(2)) + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) for (.+)$", lambda m: translate_fragment(m.group(2)) + "的" + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) of (.+)$", lambda m: translate_fragment(m.group(2)) + "的" + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) by (.+)$", lambda m: "按" + translate_fragment(m.group(2)) + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) with (.+)$", lambda m: "带" + translate_fragment(m.group(2)) + "的" + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) without (.+)$", lambda m: "不含" + translate_fragment(m.group(2)) + "的" + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) during (.+)$", lambda m: translate_fragment(m.group(2)) + "期间" + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) types?$", lambda m: translate_fragment(m.group(1)) + "类型"),
        (r"(?i)^do not (.+)$", lambda m: "不" + translate_fragment(m.group(1))),
        (r"(?i)^don't (.+)$", lambda m: "不" + translate_fragment(m.group(1))),
        (r"(?i)^not (.+)$", lambda m: "不" + translate_fragment(m.group(1))),
        (r"(?i)^add (?:a |an |the )?(.+)$", lambda m: "添加" + translate_fragment(m.group(1))),
        (r"(?i)^show/?hide (.+)$", lambda m: "显示或隐藏" + translate_fragment(m.group(1))),
        (r"(?i)^show (.+)$", lambda m: "显示" + translate_fragment(m.group(1))),
        (r"(?i)^hide (.+)$", lambda m: "隐藏" + translate_fragment(m.group(1))),
        (r"(?i)^delete (.+)$", lambda m: "删除" + translate_fragment(m.group(1))),
        (r"(?i)^create (.+)$", lambda m: "创建" + translate_fragment(m.group(1))),
        (r"(?i)^copy (.+)$", lambda m: "复制" + translate_fragment(m.group(1))),
        (r"(?i)^new (.+)$", lambda m: "新建" + translate_fragment(m.group(1))),
        (r"(?i)^search (.+)$", lambda m: "搜索" + translate_fragment(m.group(1))),
        (r"(?i)^(.+?) name$", lambda m: translate_fragment(m.group(1)) + "名称"),
        (r"(?i)^(.+?) date$", lambda m: translate_fragment(m.group(1)) + "日期"),
        (r"(?i)^id (.+)$", lambda m: translate_fragment(m.group(1)) + "编号"),
    ]
    for pattern, builder in patterns:
        match = re.match(pattern, source)
        if match and not re.search(r"[\ue000-\uf8ff]", match.group(0)):
            # Avoid recursive explosion on a pattern that doesn't shrink.
            if len(match.group(0)) < len(source) or match.group(0).lower() != source.lower() or pattern != patterns[-1][0]:
                built = builder(match)
                if built and built != source:
                    return built

    working = source
    for phrase, zh in PHRASES_SORTED:
        working = re.sub(
            r"(?i)(?<![A-Za-z])" + re.escape(phrase) + r"(?![A-Za-z])",
            zh,
            working,
        )
    parts = []
    for piece in WORD.findall(working):
        if piece.isspace():
            continue
        if re.search(r"[\ue000-\uf8ff]", piece):
            parts.append(piece)
            continue
        if re.fullmatch(r"[0-9]+(?:\.[0-9]+)?%?", piece):
            parts.append(piece)
            continue
        if piece in {"/", "-", "–", "—", "+", "&"}:
            parts.append("和" if piece == "&" else piece)
            continue
        if re.fullmatch(r"[^\w]+", piece, flags=re.UNICODE):
            if CJK.search(piece):
                parts.append(piece)
            continue
        if CJK.search(piece):
            parts.append(piece)
            continue
        lower = piece.lower()
        if lower in DROP_WORDS:
            continue
        translated = lookup_word(piece)
        if translated is None:
            parts.append(piece)
        elif translated:
            parts.append(translated)
    result = "".join(parts)
    result = result.replace("的的", "的").replace("和和", "和")
    return result


def translate_value(text):
    protected, tokens = protect(text)
    return sanitize(restore(translate_fragment(protected), tokens))


def apply_replacements(text):
    for old, new in REPLACEMENTS:
        text = text.replace(old, new)
    return text


def ensure_extra(path: Path):
    text = path.read_text(encoding="utf-8")
    existing, _ = parse(path)
    missing = [(key, value) for key, value in EXTRA_EN.items() if key not in existing]
    if not missing:
        return
    lines = text.splitlines()
    insert_at = None
    for index, line in enumerate(lines):
        if line.startswith("currentLocaleOfFile:"):
            insert_at = index
            break
    if insert_at is None:
        raise SystemExit(f"currentLocaleOfFile not found in {path}")
    extra_lines = [f'{key}: "{value}",' for key, value in missing]
    lines[insert_at:insert_at] = extra_lines
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ensure_extra(EN_PATH)
