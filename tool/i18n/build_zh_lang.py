    for key in order:
        en_value = en[key]
        if key in OVERRIDES:
            value = OVERRIDES[key]
        elif key in sentences:
            value = sentences[key]
        else:
            old = zh.get(key, "")
            if old and CJK.search(old):
                value = apply_replacements(old)
            else:
                value = translate_value(en_value)
                for word in re.findall(r"[A-Za-z][A-Za-z'\-]{2,}", value):
                    missing_words[word] = missing_words.get(word, 0) + 1
        value = sanitize(value) if key != "currentLocaleOfFile" else value
        if key == "currentLocaleOfFile":
            value = "zh"
        out_lines.append(f'{key}: "{value}",')
    # Drop the comma on the last property.
    if len(out_lines) > 1:
        out_lines[-1] = out_lines[-1].rstrip(",")
    out_lines.append("}")
    ZH_PATH.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    print(f"wrote {ZH_PATH} ({len(order)} keys)")
    print(f"sentence overrides: {len(sentences)}")
    if missing_words:
        top = sorted(missing_words.items(), key=lambda item: -item[1])[:40]
        print("remaining latin tokens:")
        for word, count in top:
            print(f"  {count:4} {word}")


