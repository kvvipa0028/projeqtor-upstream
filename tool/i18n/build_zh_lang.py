def parse(path: Path):
    keys = {}
    order = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = LINE.match(line)
        if match:
            keys[match.group(1)] = match.group(2)
            order.append(match.group(1))
    return keys, order


def load_sentences():
    found = {}
    for path in (UI_PATH, SENTENCE_PATH):
        if not path.exists():
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip() or line.startswith("#") or "\t" not in line:
                continue
            key, value = line.split("\t", 1)
            found[key] = value
    return found


def marker_for(index):
    # Private-use characters stay intact when the word splitter runs.
    return chr(0xE000 + index)


def protect(text):
    tokens = []

    def repl(match):
        tokens.append(match.group(0))
        return marker_for(len(tokens) - 1)

    return TOKEN.sub(repl, text), tokens


def restore(text, tokens):
    for index, token in enumerate(tokens):
        text = text.replace(marker_for(index), token)
    return text


def sanitize(text):
    text = text.replace('"', "&#34;")
    text = text.replace(",", "&#44;")
    text = text.replace(":", "&#58;")
    text = text.replace("\n", " ")
    text = re.sub(r"\s+", " ", text).strip()
    text = text.replace("的的", "的")
    return text


